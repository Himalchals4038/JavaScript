let a = 125, b = 4;
console.log("a + b =",a+b);
console.log("a - b =",a-b);
console.log("a * b =",a*b);
console.log("a / b =",a/b); //returns float value

console.log("a % b =",a%b);
console.log("a ** b =",a**b);

//Post-operators
console.log("a++ =",a++);
console.log("a-- =",a--);

//Pre-operators
console.log("++a =",++a);
console.log("--a =",--a);

