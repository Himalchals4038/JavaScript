let arr = [25, 48, 67, 49, 91];

//Inserts an element at the end
arr.push(50, 22, 41);
console.log(...arr);

//Removes the last element
arr.pop();
console.log(...arr);

//Inserts an element at the beginning
arr.unshift(67, 38);
console.log(...arr);

//Removes the first element
arr.shift();
console.log(...arr);

//Reverses the array
arr.reverse();
console.log(...arr);

//Sorts the array
arr.sort();
console.log(...arr);

//Joins the array
let greet = ['Thank', 'you', 'for', 'visiting', 'our', 'website.'];
console.log(greet.join(' '));